"""Expand a one-frame workflow into N frames in ONE prompt that share the model loaders (disposable Phase 1 tooling).

With the toolbox's --cache-none, every prompt reloads every model (~90 s of a ~130 s Qwen Edit frame). One prompt with
N per-frame branches loads the models once. Nodes reachable from a --shared node set are shared; every other node is
copied per frame with id "<id>_<i>", and each param named in --per-frame becomes "<param>_<i>" in the generated
params.yaml, so benchmark/tools/run_track.py patches it as usual (--input control_image_3=... --set seed_3=...).

    uv run --no-project --with pyyaml python -I benchmark/tools/batch_frames.py workflows/pose/qwen_edit_pose_native.json \
      OUT.json --frames 7 --shared 10,12,61,74,67,64,41 --per-frame control_image,seed
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("workflow", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--frames", type=int, required=True)
    ap.add_argument("--shared", required=True, help="node ids loaded once (loaders, reference image)")
    ap.add_argument("--per-frame", required=True, help="params that differ per frame")
    a = ap.parse_args(argv)
    wf = json.loads(a.workflow.read_text())
    params = yaml.safe_load(a.workflow.with_suffix(".params.yaml").read_text())
    shared = set(a.shared.split(","))
    assert shared <= set(wf), f"unknown shared ids {shared - set(wf)}"
    per_frame = a.per_frame.split(",")

    def rename(node_id: str, i: int) -> str:
        return node_id if node_id in shared else f"{node_id}_{i}"

    out: dict = {k: wf[k] for k in shared}
    for i in range(a.frames):
        for k, node in wf.items():
            if k in shared:
                continue
            inputs = {n: [rename(v[0], i), v[1]] if isinstance(v, list) and len(v) == 2 and v[0] in wf else v
                      for n, v in node["inputs"].items()}
            if "filename_prefix" in inputs:
                inputs["filename_prefix"] = f"{inputs['filename_prefix']}_f{i:02d}"
            out[rename(k, i)] = {**node, "inputs": inputs}

    def targets(spec, i: int):
        specs = spec if isinstance(spec, list) else [spec]
        return [{"node": rename(s["node"], i), "input": s["input"]} for s in specs]

    new_params: dict = {}
    for key, spec in params.items():
        if key in per_frame:
            for i in range(a.frames):
                new_params[f"{key}_{i}"] = targets(spec, i)
        else:   # shared value: patch every copy (or the one shared node)
            new_params[key] = [t for i in range(a.frames) for t in targets(spec, i)]
            new_params[key] = [dict(t) for t in {(t["node"], t["input"]): t for t in new_params[key]}.values()]
    a.out.write_text(json.dumps(out, indent=2) + "\n")
    a.out.with_suffix(".params.yaml").write_text(
        f"# generated by benchmark/tools/batch_frames.py from {a.workflow} ({a.frames} frames)\n"
        + "".join(f"{k}: [" + ", ".join(f'{{node: "{t["node"]}", input: "{t["input"]}"}}' for t in v) + "]\n"
                  for k, v in new_params.items()))
    print(f"{len(out)} nodes ({len(shared)} shared) -> {a.out}")


if __name__ == "__main__":
    main()
